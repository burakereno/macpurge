/// Pure presentation of saved scan evidence, including reports from older versions.
struct InventoryExplanation {
  let purpose: String
  let origin: String
  let finding: String
  let impact: String
  let uncertainty: String?

  init(item: ReportItem) {
    let evidence = item.evidence
    let profile = item.profile
    let kind = evidence?.kind ?? Self.kind(profile)
    let generated = [.xcodeIntermediate, .projectBuild, .projectCache, .goBuildCache, .renderCache]
      .contains(profile)
    let owner = evidence?.owner ?? item.application?.name ?? Self.owner(profile)
    origin = owner + (evidence?.projectPath.map { " · " + $0 } ?? item.workspace.map { " · " + $0 } ?? "")
    if let kind {
      purpose = Self.purpose(kind)
    } else if generated {
      purpose = "Files generated by a build or application to speed up later work."
    } else if profile == .packageDownloads || profile == .sharedDependencies {
      purpose = "Downloaded packages and supporting files kept by a package manager."
    } else {
      purpose = "Measured application, project or system data. Its contents may include personal files."
    }
    switch evidence?.finding {
    case .missingProject: finding = "The recorded project path could not be found. It may have been moved or renamed."
    case .projectPresent: finding = "Workspace metadata points to a project that is still present."
    case .unknownProject: finding = "The project association could not be verified."
    case .remoteProject: finding = "This workspace refers to a remote project; local absence is not evidence of a leftover."
    case .registeredExtension: finding = "The editor registry lists this extension folder."
    case .unregisteredExtension: finding = "The editor registry does not list this folder. It may be an extension update or uninstall leftover."
    case .unknownRegistry: finding = "The extension registry could not be verified. No leftover conclusion was made."
    case .installedApplication: finding = "The application was identified from its bundle metadata."
    case .unmatchedApplication: finding = "No installed application matched this container. This is only a possible leftover."
    case .currentVersion: finding = "The version manager identifies this version as default or linked."
    case .olderVersion: finding = "Another version is available. Projects may still depend on this exact version."
    case .unknownVersion: finding = "The active version or project dependencies could not be verified."
    case .installerMatch: finding = "The installer name matches an installed application. Its exact version and future availability are not verified."
    case .duplicateDownload: finding = "Another download has identical verified contents. Keep the copy you need."
    case .orphanModel: finding = "A complete manifest check found no model referring to this layer."
    case .partialModel: finding = "This is an interrupted model download. A download may still be running."
    case .unknownModelReferences: finding = "Model references could not be fully verified. No cleanup is offered."
    default:
      finding = item.complete || item.status == "unavailable"
        ? item.reason : "The measurement is incomplete. Cleanup eligibility cannot be established from this result."
    }
    switch kind {
    case .workspace, .history: impact = "Editor state, conversations or project memory may be lost. These are not regenerable caches."
    case .settings: impact = "Settings or sign-in state may be lost. Manage this data in its owning application."
    case .checkpoint: impact = "Saved edit checkpoints or recovery copies may be lost."
    case .extensionFiles: impact = "Extensions may stop working. Manage them in the editor."
    case .application: impact = "The application would stop being available. This view only measures its storage."
    case .logs: impact = "Diagnostic history may be lost."
    case .toolVersion: impact = "Projects or virtual environments pinned to this version may stop working. Use the version manager to make changes."
    case .installer: impact = "Reinstalling this exact version may require this installer. Its download may no longer be available."
    case .modelFragment: impact = "A model download may have to restart. Referenced model layers are never offered for removal."
    default:
      impact = generated || kind == .cache || kind == .build
        ? "The application may rebuild or download these files again. The next launch or build may take longer."
        : kind == .update ? "The application may need to download its update again."
        : "Personal or application data may be lost. Inspect it in the owning application before making changes."
    }
    uncertainty = !item.complete ? "Only readable data is included; the measurement may be a lower bound."
      : evidence?.finding == .missingProject || evidence?.finding == .unregisteredExtension || evidence?.finding == .unmatchedApplication
        ? "This finding does not prove the data is unused. Review it before deciding."
        : generated || kind == .cache || kind == .build ? nil
        : "Modification dates do not prove when data was last used."
  }

  private static func kind(_ profile: StorageProfile?) -> InventoryEvidence.Kind? {
    switch profile {
    case .npmCache, .goBuildCache, .projectCache, .projectGradleCache, .gradleCache,
         .renderCache, .simulatorCache, .verifiedDownloads: .cache
    case .xcodeIntermediate, .xcodeOrphanIntermediate, .xcodeOrphanBuild, .projectBuild: .build
    case .logs: .logs
    default: nil
    }
  }

  private static func owner(_ profile: StorageProfile?) -> String {
    switch profile {
    case .npmCache: "npm"
    case .goBuildCache: "Go"
    case .xcodeIntermediate, .xcodeOrphanIntermediate, .xcodeOrphanBuild, .xcodeWorkspace, .simulatorCache, .simulatorData: "Xcode"
    case .gradleCache, .projectGradleCache: "Gradle"
    case .uvCache: "uv"
    default: ReviewLanguage.text("The owning tool has not been verified.")
    }
  }

  private static func purpose(_ kind: InventoryEvidence.Kind) -> String {
    switch kind {
    case .cache: "Regenerable caches kept to speed up the application."
    case .build: "Intermediate files generated while building a project."
    case .workspace: "Per-project editor state, which may include conversations and recovery data."
    case .extensionFiles: "Editor extension files, including installed versions and possible leftovers."
    case .logs: "Diagnostic records produced while the tool runs."
    case .history: "Saved conversations, sessions and project memory."
    case .settings: "Application preferences, configuration or sign-in state."
    case .checkpoint: "Edit checkpoints and recovery copies."
    case .update: "Downloaded application updates and update staging files."
    case .application: "The installed application bundle and its resources."
    case .applicationData: "Data stored by an application outside its installed bundle."
    case .toolVersion: "An installed language runtime, toolchain or package version."
    case .installer: "An application installer or a repeated download."
    case .modelFragment: "A local model layer or interrupted download fragment."
    case .other: "Other tool data whose purpose has not been verified."
    }
  }
}

struct InventoryExplanationView: View {
  let item: ReportItem

  var body: some View {
    InventoryRows(rows, id: \.title) { row in
      InventoryReadout(title: ReviewLanguage.text(row.title), amount: "", symbol: row.symbol,
                       subtitle: ReviewLanguage.text(row.detail))
    }
  }

  private var rows: [(title: String, detail: String, symbol: String)] {
    let explanation = InventoryExplanation(item: item)
    var rows: [(String, String, String)] = [
      ("What is this data?", explanation.purpose, "doc.text"),
      ("Created by", explanation.origin, "app"),
      ("Why review it?", explanation.finding, "magnifyingglass"),
      ("Effect of removal", explanation.impact, "exclamationmark.circle"),
    ]
    if let uncertainty = explanation.uncertainty {
      rows.append(("Uncertainty", uncertainty, "questionmark.circle"))
    }
    if let note = item.evidence?.note, !note.isEmpty {
      rows.append(("Evidence", note, "doc.text.magnifyingglass"))
    }
    if let management = item.evidence?.management {
      rows.append(("Manage with the owning tool", management, "terminal"))
    }
    return rows
  }
}
